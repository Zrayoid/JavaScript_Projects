// Sales Data
const salesData = [
    { product: "Laptop", category: "Electronics", quantity: 2, price: 50000 },
    { product: "Mouse", category: "Electronics", quantity: 5, price: 500 },
    { product: "Shirt", category: "Clothing", quantity: 3, price: 800 },
    { product: "Jeans", category: "Clothing", quantity: 2, price: 1500 },
    { product: "Phone", category: "Electronics", quantity: 4, price: 20000 },
    { product: "Shoes", category: "Footwear", quantity: 2, price: 2500 }
];

// Calculating Reveune for each product
const revenuePerProduct = salesData.map((data) => {
    return {
        ...data,
        Revenue: data.quantity * data.price,
    };
});

// Calculating the total revenue generated by all the products
const totalRevenue = revenuePerProduct.reduce((sum, data) => {
    return sum + data.Revenue;
}, 0);

// Average Reveneu Per Sale
const averagePerProduct = revenuePerProduct.reduce((Average, data) => {
    
    if ( salesData.length > 0)
    {
        Average = totalRevenue / salesData.length;
        return Average;
    }
    else
    {
        return 0;
    }
    
}, 0);

// Calculating total products sold
const totalItemSold = salesData.reduce((sum, data) => {
    return sum + data.quantity;
}, 0);

// Filtering product which generated the revenue of more than 5000
const highRevenueProducts = revenuePerProduct.filter((data) => {
    return data.Revenue > 5000;
});

// Filtering Revenue Based on the category
const revenuePerCategory = revenuePerProduct.reduce((tempRPC, data) => {

    if (data.category === "Electronics") {
        tempRPC.Electronics += data.Revenue;
    }
    else if (data.category === "Clothing") {
        tempRPC.Clothing += data.Revenue;
    }
    else if (data.category === "Footwear") {
        tempRPC.Footwear += data.Revenue;
    }
    return tempRPC;

},
    // initialize here
    {
        Electronics: 0,
        Clothing: 0,
        Footwear: 0
    });


// Product Which has generated the highest Revenue
const highestRevProduct = revenuePerProduct.reduce((max, data) => {
    if (max.Revenue < data.Revenue) {
        max.Product = data.product;
        max.Revenue = data.Revenue;
    }
    return max;

}, {
    Product: "",
    Revenue: 0
});

